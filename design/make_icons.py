"""Android vector drawables from design/logo.svg (the single source of the TrackDog mark).

    python design/make_icons.py

Writes app/src/main/res/drawable/ic_logo.xml (whole mark, transparent background) and
ic_launcher_foreground.xml (the same, scaled into the adaptive-icon safe zone).
Understands only what logo.svg uses: <circle> and <path> with fill / stroke attributes.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, '..', 'app', 'src', 'main', 'res', 'drawable')


def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))


def color(c, opacity):
    if not c or c == 'none':
        return None
    a = round(float(opacity) * 255) if opacity else 255
    return '#%02X%s' % (a, c.lstrip('#').upper())


def elements(svg):
    for m in re.finditer(r'<(circle|path)\b([^>]*)/>', svg, re.S):
        a = attrs(m.group(2))
        if m.group(1) == 'circle':
            cx, cy, r = float(a['cx']), float(a['cy']), float(a['r'])
            d = 'M%g %ga%g %g 0 1 0 %g 0a%g %g 0 1 0 %g 0Z' % (cx - r, cy, r, r, 2 * r, r, r, -2 * r)
        else:
            d = ' '.join(a['d'].split())
        yield d, a


def vector(svg, scale):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- generated by design/make_icons.py from design/logo.svg: do not edit -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp"',
           '    android:viewportWidth="108" android:viewportHeight="108">',
           '  <group android:pivotX="54" android:pivotY="54" android:scaleX="%g" android:scaleY="%g">' % (scale, scale)]
    for d, a in elements(svg):
        line = '    <path android:pathData="%s"' % d
        fill = color(a.get('fill', '#000000'), a.get('fill-opacity'))
        if fill:
            line += ' android:fillColor="%s"' % fill
        stroke = color(a.get('stroke'), a.get('stroke-opacity'))
        if stroke:
            line += ' android:strokeColor="%s" android:strokeWidth="%s"' % (stroke, a.get('stroke-width', '1'))
            if a.get('stroke-linecap'):
                line += ' android:strokeLineCap="%s"' % a['stroke-linecap']
        out.append(line + '/>')
    out += ['  </group>', '</vector>', '']
    return '\n'.join(out)


svg = open(os.path.join(HERE, 'logo.svg'), encoding='utf-8').read()
for name, scale in (('ic_logo.xml', 1.0), ('ic_launcher_foreground.xml', 0.78)):
    with open(os.path.join(RES, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(vector(svg, scale))
    print('wrote', name)
